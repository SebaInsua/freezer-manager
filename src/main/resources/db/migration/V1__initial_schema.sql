-- Baseline schema as it existed before user ownership and inventory batches.
-- New databases run V1 followed by V2. Existing development databases must be
-- baselined at version 1 only after verifying their schema matches this version.

CREATE TABLE foods (
    food_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(255),
    name VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL,
    CONSTRAINT uklmnpdno9yst912bustvp4vuyr UNIQUE (name),
    CONSTRAINT foods_category_check CHECK (category IS NULL OR category IN
        ('MEAT', 'VEGETABLE', 'FRUIT', 'DAIRY', 'GRAIN', 'LEGUME', 'OTHER'))
);

CREATE TABLE food_unit_of_measure (
    food_id BIGINT NOT NULL,
    unit_of_measure VARCHAR(255) NOT NULL,
    CONSTRAINT food_unit_of_measure_pkey PRIMARY KEY (food_id, unit_of_measure),
    CONSTRAINT food_unit_of_measure_unit_of_measure_check CHECK
        (unit_of_measure IN ('KG', 'G', 'UNIT')),
    CONSTRAINT fk_food_unit_of_measure_food FOREIGN KEY (food_id) REFERENCES foods(food_id)
);

CREATE TABLE storages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capacidad_litros NUMERIC(10,2) NOT NULL,
    marca VARCHAR(255),
    modelo VARCHAR(255)
);

CREATE TABLE storage_entries (
    storage_entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_date_time TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    recorded_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    storage_id BIGINT NOT NULL,
    CONSTRAINT fk_storage_entries_storage FOREIGN KEY (storage_id) REFERENCES storages(id)
);

CREATE TABLE storage_entry_details (
    entry_detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad NUMERIC(10,2) NOT NULL,
    unit_selected VARCHAR(255) NOT NULL,
    food_id BIGINT NOT NULL,
    storage_entry_id BIGINT NOT NULL,
    CONSTRAINT storage_entry_details_unit_selected_check CHECK (unit_selected IN ('KG', 'G', 'UNIT')),
    CONSTRAINT fk_storage_entry_details_food FOREIGN KEY (food_id) REFERENCES foods(food_id),
    CONSTRAINT fk_storage_entry_details_entry FOREIGN KEY (storage_entry_id) REFERENCES storage_entries(storage_entry_id)
);

CREATE TABLE storage_exits (
    storage_exit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_date_time TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    recorded_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    storage_id BIGINT NOT NULL,
    CONSTRAINT fk_storage_exits_storage FOREIGN KEY (storage_id) REFERENCES storages(id)
);

CREATE TABLE storage_exit_details (
    exit_detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad NUMERIC(10,2) NOT NULL,
    unit_selected VARCHAR(255) NOT NULL,
    food_id BIGINT NOT NULL,
    storage_exit_id BIGINT NOT NULL,
    CONSTRAINT storage_exit_details_unit_selected_check CHECK (unit_selected IN ('KG', 'G', 'UNIT')),
    CONSTRAINT fk_storage_exit_details_food FOREIGN KEY (food_id) REFERENCES foods(food_id),
    CONSTRAINT fk_storage_exit_details_exit FOREIGN KEY (storage_exit_id) REFERENCES storage_exits(storage_exit_id)
);

CREATE TABLE storage_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad NUMERIC(10,2) NOT NULL,
    food_id BIGINT NOT NULL,
    storage_id BIGINT NOT NULL,
    CONSTRAINT uk_storage_item_food_storage UNIQUE (food_id, storage_id),
    CONSTRAINT fk_storage_items_food FOREIGN KEY (food_id) REFERENCES foods(food_id),
    CONSTRAINT fk_storage_items_storage FOREIGN KEY (storage_id) REFERENCES storages(id)
);
