-- Add users, ownership, and inventory batches to the legacy schema.
-- The existing development database currently has no rows, but these changes
-- are still additive and should be reviewed before applying to any shared DB.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password VARCHAR(255) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

ALTER TABLE foods
    ADD COLUMN default_shelf_life_days INTEGER,
    ADD COLUMN estimated_weight_per_unit_kg NUMERIC(10,3),
    ADD COLUMN owner_id BIGINT;

ALTER TABLE foods
    ADD CONSTRAINT fk_foods_owner FOREIGN KEY (owner_id) REFERENCES users(id);

ALTER TABLE storages
    ADD COLUMN user_id BIGINT NOT NULL;

ALTER TABLE storages
    ADD CONSTRAINT fk_storages_owner
        FOREIGN KEY (user_id) REFERENCES users(id);

CREATE TABLE storage_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_detail_id BIGINT NOT NULL,
    initial_quantity NUMERIC(10,2) NOT NULL,
    available_quantity NUMERIC(10,2) NOT NULL,
    active BOOLEAN NOT NULL,
    expiration_date DATE,
    expiration_date_type VARCHAR(255) NOT NULL DEFAULT 'UNDEFINED',
    CONSTRAINT uk_storage_batches_entry_detail UNIQUE (entry_detail_id),
    CONSTRAINT fk_storage_batches_entry_detail
        FOREIGN KEY (entry_detail_id) REFERENCES storage_entry_details(entry_detail_id),
    CONSTRAINT storage_batches_expiration_date_type_check
        CHECK (expiration_date_type IN ('ACTUAL', 'ESTIMATED', 'UNDEFINED'))
);

ALTER TABLE storage_exit_details
    ADD COLUMN batch_id BIGINT NOT NULL;

ALTER TABLE storage_exit_details
    ADD CONSTRAINT fk_storage_exit_details_batch
        FOREIGN KEY (batch_id) REFERENCES storage_batches(id);
